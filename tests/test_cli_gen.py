from __future__ import annotations

import os
from pathlib import Path

import pytest

from puffin.cli.main import main

MAIN = "fw/main/main/include/puffin_pins.h"
MOTOR = "fw/motor/main/include/puffin_pins.h"


def gen(example_path: Path, *args: str) -> int:
    return main(["gen", str(example_path), *args])


def replace(path: Path, old: str, new: str) -> None:
    text = path.read_text()
    assert old in text
    path.write_text(text.replace(old, new, 1))


def test_creates_then_reports_unchanged(
    example_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = example_path.parent
    assert gen(example_path) == 0
    assert capsys.readouterr().out.splitlines() == [f"created {MAIN}", f"created {MOTOR}"]
    golden = Path(__file__).parent / "golden" / "dual-esp32s3-robot"
    assert (root / MAIN).read_bytes() == (golden / "main" / "puffin_pins.h").read_bytes()
    assert gen(example_path) == 0
    assert capsys.readouterr().out.splitlines() == [f"unchanged {MAIN}", f"unchanged {MOTOR}"]


def test_unchanged_files_are_not_touched(example_path: Path) -> None:
    target = example_path.parent / MAIN
    assert gen(example_path) == 0
    os.utime(target, (1_000_000_000, 1_000_000_000))
    inode = target.stat().st_ino
    assert gen(example_path) == 0
    assert target.stat().st_mtime == 1_000_000_000
    assert target.stat().st_ino == inode


def test_update_summary_counts_lines(
    example_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    assert gen(example_path) == 0
    replace(example_path, "sck: GPIO12", "sck: GPIO14")
    replace(example_path, "IMU_SCK: [U1.GPIO12", "IMU_SCK: [U1.GPIO14")
    capsys.readouterr()
    assert gen(example_path) == 0
    assert capsys.readouterr().out.splitlines() == [
        f"updated {MAIN} (+1 -1 lines)",
        f"unchanged {MOTOR}",
    ]


def test_errors_block_generation(example_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    replace(example_path, "cs.imu: GPIO10", "cs.imu: GPIO9")
    assert gen(example_path) == 1
    output = capsys.readouterr().out
    assert "assignment-unconnected" in output and "nothing generated" in output
    assert not (example_path.parent / "fw").exists()


def test_warnings_print_but_do_not_block(
    example_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    example_path.write_text(
        example_path.read_text().replace(
            "    note: boot button, intentional\n",
            "    note: boot button, intentional\n  - {pin: U1.GPIO4, allow: strapping, note: x}\n",
        )
    )
    assert gen(example_path) == 0
    output = capsys.readouterr().out
    assert "warning[unused-override]" in output and f"created {MAIN}" in output


def test_hand_written_file_is_protected(
    example_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    foreign = example_path.parent / MOTOR
    foreign.parent.mkdir(parents=True)
    foreign.write_text("// my own header\n")
    assert gen(example_path) == 1
    output = capsys.readouterr().out
    assert "was not generated by Puffin" in output and "move or delete the file" in output
    assert foreign.read_text() == "// my own header\n"
    assert not (example_path.parent / MAIN).exists()


def test_check_exit_codes(example_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    root = example_path.parent
    assert gen(example_path, "--check") == 1
    assert capsys.readouterr().out.splitlines() == [f"missing {MAIN}", f"missing {MOTOR}"]
    assert not (root / "fw").exists()
    assert gen(example_path) == 0
    assert gen(example_path, "--check") == 0
    replace(example_path, "cs.imu: GPIO10", "cs.imu: GPIO9")
    replace(example_path, "IMU_CS: [U1.GPIO10", "IMU_CS: [U1.GPIO9")
    before = (root / MAIN).read_bytes()
    capsys.readouterr()
    assert gen(example_path, "--check") == 1
    assert f"stale {MAIN} (+1 -1 lines)" in capsys.readouterr().out
    assert (root / MAIN).read_bytes() == before


def test_dry_run_prints_diff_and_writes_nothing(
    example_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    assert gen(example_path, "--dry-run") == 0
    output = capsys.readouterr().out
    assert f"+++ b/{MAIN}" in output and "+#define PUFFIN_SPI2_SCK GPIO_NUM_12" in output
    assert not (example_path.parent / "fw").exists()


def test_check_and_dry_run_are_exclusive(example_path: Path) -> None:
    with pytest.raises(SystemExit):
        gen(example_path, "--check", "--dry-run")


def test_board_option_limits_output(example_path: Path) -> None:
    assert gen(example_path, "--board", "motor") == 0
    assert (example_path.parent / MOTOR).exists()
    assert not (example_path.parent / MAIN).exists()


def test_relative_path_escape_rejected(
    example_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    replace(example_path, f"output: {MAIN}", "output: ../escaped.h")
    assert gen(example_path) == 1
    assert "output-path-escape" in capsys.readouterr().out
    assert not (example_path.parent.parent / "escaped.h").exists()


def test_symlink_escape_rejected(
    example_path: Path, tmp_path_factory: pytest.TempPathFactory, capsys: pytest.CaptureFixture[str]
) -> None:
    outside = tmp_path_factory.mktemp("outside")
    (example_path.parent / "fw").symlink_to(outside, target_is_directory=True)
    assert gen(example_path) == 1
    assert "resolves outside the project directory" in capsys.readouterr().out
    assert list(outside.iterdir()) == []

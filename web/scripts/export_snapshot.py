"""Export the frozen fixture's data for the static pin-map prototype (M4 step 2).

Run from the repo root:  uv run python web/scripts/export_snapshot.py
Writes web/src/prototype/snapshot.json. Everything comes from the real service and parser, on a
temp copy of tests/fixtures/dual-esp32s3-robot, so the prototype shows real data. The write-back
proposal needs kicad-cli.
"""

from __future__ import annotations

import json
import shutil
import tempfile
from pathlib import Path

from puffin.kicad.schematic import read_schematic, symbol_graphics
from puffin.mcp.service import PuffinService

REPO = Path(__file__).resolve().parents[2]
FIXTURE = REPO / "tests" / "fixtures" / "dual-esp32s3-robot"
OUT = REPO / "web" / "src" / "prototype" / "snapshot.json"
MOVE = [{"op": "move_pin", "component": "U1", "from_pin": "GPIO10", "to_pin": "GPIO4"}]

def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / "project"
        shutil.copytree(FIXTURE, root)
        service = PuffinService(root)
        project = service.get_project()
        pins = service.query_pins("U1")
        sch = read_schematic((root / "hw/robot/robot.kicad_sch").read_text(encoding="utf-8"))
        graphics = symbol_graphics(sch, "U1")
        by_number = {str(n): p for p in pins["pins"] for n in p["numbers"]}
        section = service.read_doc_section("espressif/esp32-s3-wroom-1#strapping-pins-table-4-1")
        snapshot = {
            "note": "Generated by web/scripts/export_snapshot.py from the frozen fixture.",
            "project": project["project"],
            "boards": sorted(project["boards"]),
            "component": "U1",
            "part": pins["part"],
            "variant": pins["variant"],
            "symbol": graphics,
            "pin_by_number": {n: p["pin"] for n, p in by_number.items()},
            "pins": {p["pin"]: p for p in pins["pins"]},
            "legal": service.legal_pins("U1", "spi2", "cs.imu"),
            "selected": "GPIO0",
            "doc": {"GPIO0": section},
            "proposal": service.propose_edit(MOVE),
            "proposal_writeback": service.propose_edit(MOVE, writeback=True),
            "check": service.check(),
        }
    OUT.write_text(json.dumps(snapshot, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()

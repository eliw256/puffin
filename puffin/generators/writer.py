"""Plans and applies generated-file writes inside a project directory.

Planning reads the filesystem but changes nothing, so callers can show a summary, a diff,
or a check result first. A plan is blocked when writing would escape the project
directory or overwrite a file that Puffin did not generate.
"""

from __future__ import annotations

import difflib
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from puffin.core.fsio import atomic_write
from puffin.generators.types import MARKER_PREFIX, GeneratedFile

Action = Literal["create", "update", "unchanged", "blocked"]


@dataclass(frozen=True)
class PlannedWrite:
    file: GeneratedFile
    target: Path
    action: Action
    previous: bytes | None = None
    reason: str = ""
    hint: str = ""

    def _lines(self) -> tuple[list[str], list[str]]:
        old = self.previous.decode("utf-8", errors="replace") if self.previous else ""
        return old.splitlines(keepends=True), self.file.content.decode("ascii").splitlines(
            keepends=True
        )

    def line_changes(self) -> tuple[int, int]:
        """(added, removed) line counts."""
        added = removed = 0
        for line in difflib.unified_diff(*self._lines(), n=0):
            if line.startswith("+") and not line.startswith("+++"):
                added += 1
            elif line.startswith("-") and not line.startswith("---"):
                removed += 1
        return added, removed

    def diff(self) -> str:
        source = f"a/{self.file.path}" if self.previous is not None else "/dev/null"
        return "".join(difflib.unified_diff(*self._lines(), source, f"b/{self.file.path}"))


def plan_writes(project_dir: Path, files: list[GeneratedFile]) -> list[PlannedWrite]:
    root = project_dir.resolve()
    plans: list[PlannedWrite] = []
    for file in files:
        target = root / file.path
        output = f"boards.{file.board}.firmware.output"
        if not target.resolve().is_relative_to(root):
            plans.append(
                PlannedWrite(
                    file,
                    target,
                    "blocked",
                    reason="resolves outside the project directory (through a symlink)",
                    hint=f"point {output} at a real directory inside the project",
                )
            )
        elif target.is_dir():
            plans.append(
                PlannedWrite(
                    file,
                    target,
                    "blocked",
                    reason="is a directory",
                    hint=f"set {output} to a file path",
                )
            )
        elif target.exists():
            previous = target.read_bytes()
            if not previous.startswith(MARKER_PREFIX):
                plans.append(
                    PlannedWrite(
                        file,
                        target,
                        "blocked",
                        previous,
                        reason="exists and was not generated by Puffin",
                        hint=f"move or delete the file, or change {output} to another path",
                    )
                )
            elif previous == file.content:
                plans.append(PlannedWrite(file, target, "unchanged", previous))
            else:
                plans.append(PlannedWrite(file, target, "update", previous))
        else:
            plans.append(PlannedWrite(file, target, "create"))
    return plans


def apply_writes(plans: list[PlannedWrite]) -> None:
    """Write every create/update plan atomically. Refuses if any plan is blocked."""
    if any(plan.action == "blocked" for plan in plans):
        raise ValueError("refusing to write: at least one output is blocked")
    for plan in plans:
        if plan.action in ("create", "update"):
            plan.target.parent.mkdir(parents=True, exist_ok=True)
            atomic_write(plan.target, plan.file.content)
